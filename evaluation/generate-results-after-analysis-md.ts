/**
 * Generates results_after_analysis.md from agent-classifications.json.
 * Groups divergences by root cause category, includes metadata about the
 * model used, and links to source/log files.
 *
 * Simplified output: only label + explanation per entry (no confidence/oracle error).
 *
 * Usage: npx tsx evaluation/generate-results-after-analysis-md.ts
 */
import * as fs from "node:fs";
import * as path from "node:path";

interface Classification {
  dataset: string;
  taskId: string;
  category: "postcondition" | "precondition" | "invariant";
  direction: "FP" | "FN";
  predicted: string;
  oracle: string;
  rootCause: string;
  explanation: string;
  confidence: number;
  oracleError: boolean;
  relativePath: string;
  logPath: string | null;
}

interface AgentClassifications {
  classifications: Classification[];
}

const repoRoot = process.cwd();
const inputPath = path.join(repoRoot, "evaluation/results/agent-classifications.json");
const agentConfigPath = path.join(repoRoot, "evaluation/agents/classify-divergence.json");
const outputPath = path.join(repoRoot, "results_after_analysis.md");

if (!fs.existsSync(inputPath)) {
  console.error(`ERROR: ${inputPath} not found.`);
  console.error("Run ./evaluation/run-classify-divergences.sh first.");
  process.exit(1);
}

const { classifications }: AgentClassifications = JSON.parse(
  fs.readFileSync(inputPath, "utf-8")
);

// Read agent config for metadata
let model = "unknown";
if (fs.existsSync(agentConfigPath)) {
  const cfg = JSON.parse(fs.readFileSync(agentConfigPath, "utf-8"));
  model = cfg.model ?? "unknown";
}

// Group by rootCause
const groups = new Map<string, Classification[]>();
for (const c of classifications) {
  const existing = groups.get(c.rootCause) ?? [];
  existing.push(c);
  groups.set(c.rootCause, existing);
}

// Sort groups by count descending
const sortedGroups = [...groups.entries()].sort((a, b) => b[1].length - a[1].length);

// Compute stats
const directionCounts = { FP: 0, FN: 0 };
const categoryCounts: Record<string, number> = {};
for (const c of classifications) {
  directionCounts[c.direction]++;
  categoryCounts[c.category] = (categoryCounts[c.category] ?? 0) + 1;
}

// --- Generate Markdown ---
const lines: string[] = [];

lines.push("# ProofPulse — Post-Analysis Divergence Report");
lines.push("");
lines.push("Auto-generated by `npx tsx evaluation/generate-results-after-analysis-md.ts`");
lines.push("");
lines.push("## Metadata");
lines.push("");
lines.push(`| Field | Value |`);
lines.push(`|-------|-------|`);
lines.push(`| Model | \`${model}\` |`);
lines.push(`| Total classifications | ${classifications.length} |`);
lines.push(`| Unique root causes | ${groups.size} |`);
lines.push(`| FP count | ${directionCounts.FP} |`);
lines.push(`| FN count | ${directionCounts.FN} |`);
lines.push(`| Generated | ${new Date().toISOString().split("T")[0]} |`);
lines.push("");

// Category breakdown
lines.push("## By Spec Category");
lines.push("");
lines.push("| Category | Count |");
lines.push("|----------|-------|");
for (const [cat, count] of Object.entries(categoryCounts).sort((a, b) => b[1] - a[1])) {
  lines.push(`| ${cat} | ${count} |`);
}
lines.push("");

// Root cause summary table
lines.push("## Root Cause Summary");
lines.push("");
lines.push("| Root Cause | Count | % |");
lines.push("|------------|-------|---|");
for (const [cause, items] of sortedGroups) {
  const pct = ((items.length / classifications.length) * 100).toFixed(1);
  lines.push(`| \`${cause}\` | ${items.length} | ${pct}% |`);
}
lines.push("");

// Detailed sections per root cause — simplified: label + explanation only
lines.push("## Detailed Classifications by Root Cause");
lines.push("");

for (const [cause, items] of sortedGroups) {
  lines.push(`### ${cause} (${items.length})`);
  lines.push("");
  lines.push(
    "| Dataset | Task | Category | Dir | Predicted | Oracle | File | Log |"
  );
  lines.push(
    "|---------|------|----------|-----|-----------|--------|------|-----|"
  );

  for (const c of items) {
    const fileLink = `[task_id_${c.taskId}.dfy](${c.relativePath})`;
    const logLink = c.logPath ? `[log](${c.logPath})` : "-";
    lines.push(
      `| ${c.dataset} | ${c.taskId} | ${c.category} | ${c.direction} | ${c.predicted} | ${c.oracle} | ${fileLink} | ${logLink} |`
    );
  }

  lines.push("");
  lines.push("<details><summary>Explanations</summary>");
  lines.push("");
  for (const c of items) {
    lines.push(
      `- **${c.dataset}/task_${c.taskId} (${c.category} ${c.direction})**: ${c.explanation}`
    );
  }
  lines.push("");
  lines.push("</details>");
  lines.push("");
}

// Write output
const output = lines.join("\n");
fs.writeFileSync(outputPath, output);
console.log(`Written ${outputPath} (${classifications.length} classifications, ${groups.size} root causes)`);
